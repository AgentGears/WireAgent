"""Layer 8 — E-2 expected-test-inventory verification.

Two modes:

  verify-collect   the collected test set of the Windows qualification
                   selection equals the checked-in manifest exactly — a
                   missing or extra scenario fails qualification BEFORE any
                   test runs.
  verify-run LOG   the post-run log's SKIPPED lines are exactly the
                   expected POSIX-gated skips (labeled legitimate); any
                   other skip fails qualification.

Manifest: tests/l8_windows_inventory.txt (one `file::test` per line,
generated by --collect-only on a Windows platform and committed).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
MANIFEST = HERE / "l8_windows_inventory.txt"

SELECTION = [
    "tests/test_m7_layer7_ownership.py",
    "tests/test_m7_layer7_crash_matrix.py",
    "tests/test_m7_layer7_t16_race.py",
    "tests/test_m7_layer7_supported_faults.py",
    "tests/test_m7_layer7_ipc_faults.py",
    "tests/test_m7_layer7_media_boundary.py",
    "tests/test_m7_layer7_browser_child.py",
    "tests/test_m7_layer7_harness_safety.py",
    "tests/test_m7_layer6_ingress.py",
]

# The ONLY skips permitted in this selection on the qualified Windows image,
# each with its legitimate platform reason (E-2: POSIX-only skips labeled).
EXPECTED_SKIPS = {
    "tests/test_m7_layer7_supported_faults.py::test_T65_endpoint_rendezvous_loss_is_not_ownership_loss":
        "POSIX-pathname fault",
}


def collected() -> set[str]:
    probe = subprocess.run(  # noqa: S603 - fixed interpreter + repo files
        [sys.executable, "-m", "pytest", "--collect-only", "-q", *SELECTION],
        capture_output=True,
        text=True,
        cwd=HERE.parent,
        timeout=300,
    )
    return {
        line.strip()
        for line in probe.stdout.splitlines()
        if line.strip().startswith("tests/") and "::" in line
    }


def verify_collect() -> int:
    expected = {line.strip() for line in MANIFEST.read_text(encoding="utf-8").splitlines() if line.strip()}
    actual = collected()
    missing = expected - actual
    extra = actual - expected
    if missing or extra:
        print(f"INVENTORY FAIL: missing={sorted(missing)} extra={sorted(extra)}", file=sys.stderr)
        return 1
    print(f"INVENTORY OK: {len(expected)} expected scenarios all present, none extra.")
    return 0


def verify_run(log_path: str) -> int:
    log = Path(log_path).read_text(encoding="utf-8", errors="replace")
    skipped = set()
    for m in re.finditer(r"^SKIPPED\s+\[([^\]]+)\]\s+(\S+::\S+)", log, re.M):
        skipped.add(m.group(2))
    # The -ra short-summary form is the primary source; also accept the
    # verbose per-test form as a fallback.
    if not skipped:
        for m in re.finditer(r"(\S+::\S+) SKIPPED", log):
            skipped.add(m.group(1))
    unexpected = skipped - set(EXPECTED_SKIPS)
    if unexpected:
        print(
            f"INVENTORY FAIL: unexpected skips in mandatory Windows-active set: {sorted(unexpected)}",
            file=sys.stderr,
        )
        return 1
    for sid, reason in EXPECTED_SKIPS.items():
        label = f"({reason})" if reason else ""
        print(f"expected skip, labeled legitimate {label}: {sid}")
    print(f"INVENTORY OK: run skips are exactly the labeled POSIX set ({len(skipped)}).")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in ("verify-collect", "verify-run"):
        print("usage: _l8_inventory.py verify-collect | verify-run LOG", file=sys.stderr)
        raise SystemExit(2)
    if sys.argv[1] == "verify-collect":
        raise SystemExit(verify_collect())
    if len(sys.argv) < 3:
        print("verify-run requires the log path", file=sys.stderr)
        raise SystemExit(2)
    raise SystemExit(verify_run(sys.argv[2]))
